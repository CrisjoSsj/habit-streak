// Función para obtener un icono por nombre
export const getHabitIcon = (iconName: string | null | undefined): LucideIcon => {
  if (!iconName) return Target; // Icono por defecto (como el logo)
  
  const normalizedName = iconName.toLowerCase().trim();
  return iconMap[normalizedName] || Target; // Si no existe, usar Target como fallback
};

// Función helper para renderizar el icono con props
export const renderHabitIcon = (
  iconName: string | null | undefined,
  className?: string,
  size?: number
) => {
  const IconComponent = getHabitIcon(iconName);
  return <IconComponent className={className} size={size} />;
};

export default iconMap;

